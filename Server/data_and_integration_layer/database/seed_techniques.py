def seed_techniques():
    with SessionLocal() as db:
        for data in TECHNIQUES:
            existing = db.execute(
                select(Technique).where(
                    Technique.name_en == data["name_en"]
                )
            ).scalar_one_or_none()

            if existing is None:
                db.add(Technique(**data))

        db.commit()

    print("Technique seed completed.")


if __name__ == "__main__":
    seed_techniques()