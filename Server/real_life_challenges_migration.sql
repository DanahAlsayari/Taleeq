CREATE TABLE IF NOT EXISTS real_life_challenges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    title TEXT NOT NULL,
    instructions TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS real_life_challenge_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,
    challenge_id BIGINT NOT NULL
        REFERENCES real_life_challenges(id),

    title TEXT NOT NULL,
    instructions TEXT NOT NULL,

    is_current BOOLEAN NOT NULL DEFAULT TRUE,
    is_completed BOOLEAN NOT NULL DEFAULT FALSE,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    reflection TEXT,
    reflection_updated_at TIMESTAMPTZ,

    CONSTRAINT challenge_completion_date_consistent CHECK (
        is_completed = (completed_at IS NOT NULL)
    ),
    CONSTRAINT challenge_reflection_length CHECK (
        reflection IS NULL OR char_length(reflection) <= 2000
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS one_current_real_life_challenge_per_user
    ON real_life_challenge_attempts(user_id)
    WHERE is_current;

CREATE INDEX IF NOT EXISTS real_life_challenge_history_by_user
    ON real_life_challenge_attempts(
        user_id, completed_at DESC, id DESC
    );

